                      'QianClouds用户服务协议与隐私政策',
                      style: TextStyle(
                          fontSize: 17, fontWeight: FontWeight.bold, color: AppColors.textMain),
                    ),
                    const SizedBox(height: 6),
                    const Text('最后更新日期：2026年8月',
                        style: TextStyle(fontSize: 12, color: AppColors.textWeak)),
                    const SizedBox(height: 12),
                    _paragraph(_kIntro),
                    for (final part in _kParts) ...[
                      const SizedBox(height: 16),
                      Text(part.title,
                          style: const TextStyle(
                              fontSize: 15,
                              fontWeight: FontWeight.bold,
                              color: AppColors.textMain)),
                      for (final section in part.sections) ...[
                        const SizedBox(height: 12),
                        Text(section.head,
                            style: const TextStyle(
                                fontSize: 14,
                                fontWeight: FontWeight.w600,
